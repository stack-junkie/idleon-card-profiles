  console.log(JSON.stringify({ passed: true, checks: ['native font', 'double-click rename', 'Enter/Escape/blur', 'keyboard isolation and held key release', 'slot and character isolation', 'cancel on native preset/menu change', 'save whole profile', 'explicit profile update', 'load complete profile', 'unswitched cards captured', 'recovery', 'collapsed group details', 'dynamic Load group name', 'on-demand help', 'delete cancel and confirmation', 'modal keyboard focus', 'menu visibility', 'scaling', 'persistence across reload'], screenshots: output }, null, 2));
