  assert.match(await page.locator('#equipped-state').textContent(), /Frog/);
  await page.getByRole('button', { name: 'Load card profile', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'idleon-card-profiles-library.png'), fullPage: true });
  assert.equal(await page.getByRole('button', { name: 'Load', exact: true }).isDisabled(), true);
  assert.equal(await page.locator('.icp-details').count(), 0);
  assert.equal(await page.getByRole('button', { name: /Import|Export/ }).count(), 0);
  await page.getByRole('button', { name: 'Expand General setup updated', exact: true }).click();
