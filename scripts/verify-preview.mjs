  await page.locator('#menu').uncheck(); await page.locator('[data-action=name]').waitFor({ state: 'hidden' });
  await page.locator('#menu').check();
  await wait(page, () => document.querySelector('[data-action=name]').getAttribute('aria-label').startsWith('Bossing.'));
  await page.getByRole('button', { name: 'Select preset 2', exact: true }).click();
  await page.locator('[data-action=name]').dblclick(); await page.locator('.icp-edit').fill('Mining');
  await page.locator('footer').click();
  await wait(page, () => document.querySelector('[data-action=name]').getAttribute('aria-label').startsWith('Mining.'));
  await page.getByRole('button', { name: 'Select preset 1', exact: true }).click();
  await page.getByRole('button', { name: 'Save card profile', exact: true }).click();
  await page.getByLabel('Group name', { exact: true }).fill('General setup');
  await page.getByRole('button', { name: 'Save group', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Save card profile', exact: true }).click();
  await page.getByLabel('Save as', { exact: true }).selectOption({ label: 'Update: General setup' });
  await page.getByLabel('Group name', { exact: true }).fill('General setup updated');
  await page.getByRole('button', { name: 'Update group', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.locator('[data-action=name]').dblclick(); await page.locator('.icp-edit').fill('Must cancel on character');
  await page.locator('#character').selectOption('Mage');
