  await page.getByRole('button', { name: 'About card groups', exact: true }).click();
  await page.getByRole('heading', { name: 'ABOUT CARD GROUPS' }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'General setup updated', exact: true }).click();
  await page.getByRole('button', { name: 'Load General setup updated', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await wait(page, () => document.querySelector('[data-action=name]').getAttribute('aria-label').startsWith('Bossing.'));
  assert.match(await page.locator('#equipped-state').textContent(), /Green Mushroom/);
  await page.getByRole('button', { name: 'Select preset 2', exact: true }).click();
  await wait(page, () => document.querySelector('[data-action=name]').getAttribute('aria-label').startsWith('Mining.'));
  await page.getByRole('button', { name: 'Select preset 1', exact: true }).click();
