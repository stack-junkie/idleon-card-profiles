  await page.locator('[data-action=name]').dblclick(); await page.locator('.icp-edit').fill('Must cancel on switch');
  await page.getByRole('button', { name: 'Select preset 2', exact: true }).click();
  await wait(page, () => document.querySelector('[data-action=name]').getAttribute('aria-label').startsWith('Preset 2.'));
  await page.getByRole('button', { name: 'Select preset 1', exact: true }).click();
  await wait(page, () => document.querySelector('[data-action=name]').getAttribute('aria-label').startsWith('Bossing.'));
